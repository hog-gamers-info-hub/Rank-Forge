-- Minimal, privacy-preserving daily activity counters.  The event table is
-- write-only to authenticated clients; the private aggregate view is for a
-- trusted admin/service process only.

create table public.activity_events (
    id uuid primary key default gen_random_uuid(),
    event_type text not null,
    occurred_at timestamptz not null default now(),
    owner_id uuid not null default auth.uid()
        references auth.users(id) on delete cascade,
    constraint activity_events_event_type_check
        check (event_type in (
            'result_downloaded',
            'standings_share_initiated',
            'custom_design_saved'
        ))
);

create index activity_events_occurred_at_event_type_idx
    on public.activity_events (occurred_at, event_type);

alter table public.activity_events enable row level security;

-- Clients may submit only the allow-listed event name.  The timestamp and
-- owner are generated by Postgres from the authenticated request context.
revoke all on table public.activity_events from public, anon, authenticated, service_role;
grant insert (event_type) on table public.activity_events to authenticated;

create policy activity_events_insert_authenticated
on public.activity_events
for insert
to authenticated
with check ((select auth.uid()) = owner_id);

-- Keep the aggregate outside the exposed API schemas.  The view is
-- SECURITY DEFINER by default, but only service_role receives schema and
-- SELECT privileges, so ordinary application roles cannot query it or the
-- underlying event rows.
create schema if not exists private;
revoke usage on schema private from public, anon, authenticated, service_role;
grant usage on schema private to service_role;

create view private.daily_activity_statistics as
select
    (occurred_at at time zone 'Asia/Kolkata')::date as activity_date,
    count(*) filter (where event_type = 'result_downloaded')::bigint
        as result_downloaded_count,
    count(*) filter (where event_type = 'standings_share_initiated')::bigint
        as standings_share_initiated_count,
    count(*) filter (where event_type = 'custom_design_saved')::bigint
        as custom_design_saved_count
from public.activity_events
group by 1
order by activity_date;

revoke all on table private.daily_activity_statistics
from public, anon, authenticated, service_role;
grant select on table private.daily_activity_statistics to service_role;
